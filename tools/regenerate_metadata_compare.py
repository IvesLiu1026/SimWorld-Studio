    parser.add_argument("--model", default=os.environ.get("CODEX_MODEL", "gpt-5.5"))
    parser.add_argument("--models", help="Comma-separated Codex models. Overrides --model.")
    parser.add_argument("--reasoning-efforts", default="default", help="Comma-separated efforts: default, low, medium, high, xhigh.")
    parser.add_argument("--codex-bin", default=os.environ.get("CODEX_BIN", "codex"))
    parser.add_argument("--timeout", type=int, default=300)
    parser.add_argument("--dry-run", action="store_true", help="Write selected_assets.json only; do not call the model.")
    parser.add_argument("--force", action="store_true", help="Regenerate even when benchmark JSONs already exist.")
    args = parser.parse_args()

    asset_db_dir = Path(args.asset_db_dir)
    records = find_catalog_records(asset_db_dir)
    if not records:
        print(f"ERROR: no catalog records found under {asset_db_dir}/catalog", file=sys.stderr)
        return 1

    asset_ids = parse_asset_ids(args.asset_ids, args.asset_id_file)
    if not asset_ids and args.manifest:
        asset_ids = select_from_manifest(Path(args.manifest), args.limit)
    if not asset_ids:
        asset_ids = select_balanced(records, args.limit)
    asset_ids = asset_ids[: args.limit]

    missing = [asset_id for asset_id in asset_ids if asset_id not in records]
    if missing:
        print("ERROR: selected asset IDs missing from current catalog:", ", ".join(missing), file=sys.stderr)
        return 1

    timestamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%d_%H%M%S")
    out_dir = Path(args.output_dir) if args.output_dir else asset_db_dir / "metadata_compare" / timestamp
    out_dir.mkdir(parents=True, exist_ok=True)

    selected = {
        "asset_db_dir": str(asset_db_dir),
        "models": parse_models(args.model, args.models),
        "reasoning_efforts": parse_reasoning_efforts(args.reasoning_efforts),
        "schema": str(Path(args.schema)),
        "asset_ids": asset_ids,
    }
    write_json(out_dir / "selected_assets.json", selected)
    print(f"selected {len(asset_ids)} assets -> {out_dir / 'selected_assets.json'}")
    if args.dry_run:
        return 0

    model_results: dict[str, list[dict[str, Any]]] = {}
    summaries: dict[str, dict[str, Any]] = {}
    all_usage: dict[str, list[dict[str, Any]]] = {}
    for model in parse_models(args.model, args.models):
      for reasoning_effort in parse_reasoning_efforts(args.reasoning_efforts):
        variant_label = f"{model}/{reasoning_effort}"
        model_dir = out_dir / "models" / safe_variant_name(model, reasoning_effort)
        regenerated_dir = model_dir / "regenerated"
        usage_dir = model_dir / "usage"
        comparisons: list[dict[str, Any]] = []
        usage_records: list[dict[str, Any]] = []
        for idx, asset_id in enumerate(asset_ids, start=1):
            old = load_json(records[asset_id])
            views = existing_view_paths(asset_db_dir, old)
            if len(views) < 1:
                raise RuntimeError(f"{asset_id}: no render views found")
            out_json = regenerated_dir / f"{asset_id}.json"
            usage_json = usage_dir / f"{asset_id}.json"
            if out_json.exists() and not args.force:
                new = load_json(out_json)
                print(f"[{variant_label} {idx}/{len(asset_ids)}] reuse {asset_id}", flush=True)
                usage_rec = load_json(usage_json) if usage_json.exists() else {
                    "asset_id": asset_id,
                    "model": model,
                    "reasoning_effort": reasoning_effort,
                    "usage": None,
                }
            else:
                print(f"[{variant_label} {idx}/{len(asset_ids)}] regenerating {asset_id} from {len(views)} views", flush=True)
                tmp_output = model_dir / "_tmp_vlm_out.json"
                vlm, trace = run_vlm(
                    rec=old,
                    view_paths=views,
                    schema=Path(args.schema),
                    model=model,
                    reasoning_effort=reasoning_effort,
                    codex_bin=args.codex_bin,
                    tmp_output=tmp_output,
                    timeout=args.timeout,
                )
                new = assemble_record(old, vlm, model)
                write_json(out_json, new)
                usage_rec = {
                    "asset_id": asset_id,
                    "model": model,
                    "reasoning_effort": reasoning_effort,
                    "thread_id": trace.get("thread_id"),
                    "usage": trace.get("usage"),
                    "returncode": trace.get("returncode"),
                    "raw_event_count": trace.get("raw_event_count"),
                }
                write_json(usage_json, usage_rec)
                usage = usage_rec.get("usage") or {}
                print(
                    "[{variant} {idx}/{total}] usage input={input} cached={cached} output={output} reasoning={reasoning}".format(
                        variant=variant_label,
                        idx=idx,
                        total=len(asset_ids),
                        input=usage.get("input_tokens"),
                        cached=usage.get("cached_input_tokens"),
                        output=usage.get("output_tokens"),
                        reasoning=usage.get("reasoning_output_tokens"),
                    ),
                    flush=True,
                )
            comparisons.append(compare_records(old, new))
            usage_records.append(usage_rec)
            write_json(model_dir / "comparison.json", comparisons)
            (model_dir / "comparison.md").write_text(markdown_report(variant_label, comparisons), encoding="utf-8")
            summaries[variant_label] = summarize_model(comparisons, usage_records)
            model_results[variant_label] = comparisons
            all_usage[variant_label] = usage_records
            write_json(out_dir / "summary.json", summaries)
            write_json(out_dir / "usage.json", all_usage)
            (out_dir / "report.md").write_text(
                combined_report(asset_ids=asset_ids, model_results=model_results, summaries=summaries),
                encoding="utf-8",
            )
        tmp_output = model_dir / "_tmp_vlm_out.json"
        if tmp_output.exists():
            tmp_output.unlink()
    print(f"wrote model outputs under {out_dir / 'models'}")
    print(f"wrote combined report to {out_dir / 'report.md'}")
    return 0


